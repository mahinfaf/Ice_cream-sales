import pandas as pd
import numpy as np
import pickle
from sklearn.linear_model import LinearRegression

# Generate synthetic dataset with 2 features
np.random.seed(42)
n_samples = 100

temperature = np.random.uniform(15, 35, n_samples)
weekend = np.random.choice([0, 1], size=n_samples, p=[0.7, 0.3])
sales = 50 + (temperature * 12) + (weekend * 80) + np.random.normal(0, 15, n_samples)

df = pd.DataFrame({'temperature': temperature, 'weekend': weekend, 'sales': sales})

# Train Linear Regression Model
X = df[['temperature', 'weekend']]
y = df['sales']

model = LinearRegression()
model.fit(X, y)

# Save as binary file using protocol=4 for maximum compatibility
with open('model.pkl', 'wb') as f:
    pickle.dump(model, f, protocol=4)

